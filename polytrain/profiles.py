"""Hardware profiles — one flag to switch between the dev box and the workstation.

Everything about a run that should change with the machine lives here, so the
training code stays hardware-agnostic and there is exactly one place to look when
a run is mis-sized.

    python -m polytrain.train_league --profile laptop      # dev / smoke
    python -m polytrain.train_league --profile workstation # the 4x Blackwell box

A NOTE ON SCALING THIS WORKLOAD
-------------------------------
The workstation guidance written for large language models does not transfer
here, and following it literally would waste effort:

* **FSDP / DeepSpeed ZeRO-3 shard a model that doesn't fit on one GPU.** Ours is
  6.15M parameters — 24.6 MB in fp32. It fits in a rounding error of one 96 GB
  card. Sharding would add all-gather traffic to solve a problem we do not have.
  Data-parallel (DDP) across GPUs is the right tool *if* gradients ever dominate;
  today they do not.
* **Transformer Engine targets transformer blocks.** Our trunk is convolutional
  (3x3 convs + squeeze-excitation), so TE's fused attention/linear kernels don't
  apply. BF16 autocast is the safe, real win; FP8 on convolutions is plausible on
  Blackwell but must be validated against a BF16 reference before being trusted,
  because RL value heads are numerically touchier than a language-model loss.
* **`num_workers` / `pin_memory` are DataLoader settings for a fixed dataset.**
  We have no dataset: every sample is generated by self-play as we train. The
  equivalent knob is `env_workers` — processes stepping the game engine.

What *actually* unlocks this box, in order of value:

1. **96 CPU cores.** Rollout generation is CPU-bound (engine stepping, mask
   building, observation encoding). This is the bottleneck today and it scales
   almost linearly with cores.
2. **4 GPUs for concurrent league agents.** The plan's league wants a main
   learner plus exploiters. One GPU each is simpler and more useful than
   sharding one model four ways.
3. **384 GB VRAM lets the network grow ~50x** — but only pays off alongside far
   more parallel environments, or the bigger net just makes rollouts slower.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field


@dataclass
class Profile:
    """A named hardware configuration."""
    name: str
    # network
    channels: int
    blocks: int
    # rollout shape
    games: int
    rollout: int
    env_workers: int              # processes stepping the engine (not DataLoader workers)
    worker_device: str            # inference device inside those processes
    # optimisation
    minibatch: int
    epochs: int
    precision: str                # "fp32" | "bf16" | "fp8"
    # curriculum / scale
    size: int
    max_turns: int
    league_size: int
    notes: str = ""
    extras: dict = field(default_factory=dict)

    def apply(self, args) -> None:
        """Fill argparse values the user did not set explicitly."""
        given = _explicit_flags()
        for key in ("channels", "blocks", "games", "rollout", "minibatch",
                    "epochs", "size", "max_turns", "league_size"):
            if key not in given and hasattr(args, key):
                setattr(args, key, getattr(self, key))
        if "workers" not in given and hasattr(args, "workers"):
            args.workers = self.env_workers
        if "worker_device" not in given and hasattr(args, "worker_device"):
            args.worker_device = self.worker_device
        if "precision" not in given and hasattr(args, "precision"):
            args.precision = self.precision


def _explicit_flags() -> set[str]:
    import sys
    return {a.lstrip("-").replace("-", "_").split("=")[0]
            for a in sys.argv[1:] if a.startswith("--")}


# --- the profiles --------------------------------------------------------------
LAPTOP = Profile(
    name="laptop",
    channels=48, blocks=4,
    games=64, rollout=64,
    env_workers=8, worker_device="cpu",
    minibatch=1024, epochs=3, precision="fp32",
    size=9, max_turns=60, league_size=12,
    notes="RTX PRO 1000 (8 GB) + 16-core hybrid CPU. Small net so CPU rollout "
          "workers are a win; see polytrain/parallel.py for the measurements.",
)

SMOKE = Profile(
    name="smoke",
    channels=48, blocks=4,
    games=16, rollout=64,
    env_workers=0, worker_device="cpu",
    minibatch=1024, epochs=3, precision="fp32",
    size=6, max_turns=40, league_size=8,
    notes="Tiny 6x6 sanity run: should beat RandomLegal within minutes.",
)

WORKSTATION = Profile(
    name="workstation",
    # ~50x the parameters. Still trivial for 96 GB, but rollout cost grows with
    # it, which is why env_workers grows too.
    channels=384, blocks=20,
    games=1024, rollout=128,
    env_workers=64, worker_device="cuda",
    minibatch=8192, epochs=3, precision="bf16",
    size=11, max_turns=100, league_size=40,
    notes="4x RTX PRO 6000 Blackwell (96 GB each) + Threadripper PRO. "
          "Model is data-parallel, NOT sharded: it fits on one card many times "
          "over. Scale envs and league seats, not FSDP.",
    extras={"learner_gpu": 0, "rollout_gpus": [1, 2, 3], "league_seats": 4},
)

PROFILES = {p.name: p for p in (SMOKE, LAPTOP, WORKSTATION)}


def get(name: str) -> Profile:
    if name not in PROFILES:
        raise SystemExit(f"unknown profile {name!r}; choose from {sorted(PROFILES)}")
    return PROFILES[name]


def autodetect() -> str:
    """Best-guess profile from the visible hardware."""
    try:
        import torch
        gpus = torch.cuda.device_count()
        vram = (torch.cuda.get_device_properties(0).total_memory / 1e9
                if gpus else 0.0)
    except Exception:
        gpus, vram = 0, 0.0
    cores = os.cpu_count() or 1
    if gpus >= 2 and vram >= 40 and cores >= 48:
        return "workstation"
    return "laptop"


def describe(profile: Profile) -> str:
    return (f"profile={profile.name} net={profile.channels}x{profile.blocks} "
            f"games={profile.games} rollout={profile.rollout} "
            f"env_workers={profile.env_workers}({profile.worker_device}) "
            f"minibatch={profile.minibatch} precision={profile.precision} "
            f"size={profile.size}\n  {profile.notes}")
